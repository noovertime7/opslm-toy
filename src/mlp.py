import torch
import torch.nn as nn
import torch.nn.functional as F


class MLP(nn.Module):

    def __init__(
        self,
        d_model: int,
        d_ff: int,
        dropout: float = 0.1,
    ):
        super().__init__()

        # ====================================================
        # 第一层
        #
        # 512 -> 2048
        # ====================================================

        self.fc1 = nn.Linear(
            d_model,
            d_ff,
        )

        # ====================================================
        # 第二层
        #
        # 2048 -> 512
        # ====================================================

        self.fc2 = nn.Linear(
            d_ff,
            d_model,
        )

        # ====================================================
        # Dropout
        # ====================================================

        self.dropout = nn.Dropout(
            dropout
        )

    def forward(
        self,
        x: torch.Tensor,
    ) -> torch.Tensor:

        # x:
        #
        # [B, T, d_model]

        # ====================================================
        # 1. 扩展维度
        #
        # [B,T,512]
        # ->
        # [B,T,2048]
        # ====================================================

        x = self.fc1(x)

        # ====================================================
        # 2. 激活函数
        # ====================================================

        x = F.gelu(x)

        # ====================================================
        # 3. 压回原维度
        #
        # [B,T,2048]
        # ->
        # [B,T,512]
        # ====================================================

        x = self.fc2(x)

        # ====================================================
        # 4. Dropout
        # ====================================================

        x = self.dropout(x)

        return x
